#!/bin/sh
# Checks TLS behavior against IP-literal targets end to end by running the
# full example Docker Compose stack with a locally built package. There are
# two independent gaps involved:
#
#  1. On every startup, the modular input calls back into Splunk's own
#     management API at the literal https://127.0.0.1:8089 (see
#     internal/auth/auth.go), which must succeed against Splunk's
#     self-signed default certificate for the input to ever listen. The
#     wait loop below catches a regression here directly: if this call
#     fails, the OTLP ports never open.
#  2. Separately, the server certificate generated by generate-certs.sh for
#     the receiver's own TLS listener must carry an IP SAN, not just DNS
#     SANs ("splunk", "localhost"), so a TLS client dialing the receiver by
#     IP address succeeds the same way a client dialing it by hostname
#     does. The checks after the wait loop cover that.
#
# It then sends logs, metrics and traces through the receiver and checks that
# the output of the splunk_modinput exporter was indexed by Splunk.
#
# Usage: OTLP_PACKAGE_PATH=/path/to/splunk-connect-for-otlp.tgz sh test-ip-sans.sh
#
# Required environment variables:
#   OTLP_PACKAGE_PATH  Path to a locally built splunk-connect-for-otlp.tgz
# Optional environment variables:
#   TEST_HEC_PAGINATION  Set to 1 to reproduce OTL-4676 with 61 HEC tokens
#   TEST_KEEP_RUNNING    Set to 1 to leave the Docker Compose stack (and the
#                        Splunk Web UI) up after the test instead of tearing
#                        it down, so the result can be inspected manually.

set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

: "${OTLP_PACKAGE_PATH:?OTLP_PACKAGE_PATH must point to a locally built splunk-connect-for-otlp.tgz}"
OTLP_PACKAGE_PATH="$(cd "$(dirname "$OTLP_PACKAGE_PATH")" && pwd)/$(basename "$OTLP_PACKAGE_PATH")"

COMPOSE="docker compose -f docker-compose.yml -f docker-compose.test.yml --profile splunk"
HTTP_PORT=4318
# HEC token accepted by the receiver, seeded into inputs.conf before startup.
SMOKE_TOKEN="00000000-0000-0000-0000-00000000feed"
WORKDIR="$(mktemp -d)"
CA_CRT="$WORKDIR/ca.crt"

cleanup() {
    status=$?
    if [ "$status" -ne 0 ]; then
        echo "==> Failure detected, dumping otlp-related splunkd.log lines"
        $COMPOSE exec -T -u root splunk grep -i otlp /opt/splunk/var/log/splunk/splunkd.log || true
    fi
    if [ "${TEST_KEEP_RUNNING:-0}" = 1 ]; then
        echo "==> TEST_KEEP_RUNNING set, leaving Docker Compose stack running"
        echo ""
        echo "Splunk Web UI: http://localhost:18000"
        echo "  Username: admin"
        echo "  Password: VH#ou812@5150"
        echo ""
        echo "Useful commands:"
        echo "  View splunkd logs: docker compose -p example exec -T -u root splunk tail -f /opt/splunk/var/log/splunk/splunkd.log"
        echo "  Tear down stack: docker compose -p example down -v && rm -rf \"$WORKDIR\""
        echo ""
        exit "$status"
    fi
    # Splunk's Ansible-based provisioning runs as root and chowns the
    # bind-mounted app directory (see docker-compose.test.yml) to its
    # internal splunk user. Docker Desktop's VM-backed bind mounts hide
    # this by remapping ownership back to the host user, but native Linux
    # Docker (as used in CI) does not, leaving root-owned files that the
    # unprivileged rm -rf below can't delete. Reclaim ownership through the
    # container itself before tearing the stack down.
    $COMPOSE exec -T -u root splunk chown -R "$(id -u):$(id -g)" /opt/splunk/etc/apps/splunk-connect-for-otlp || true
    echo "==> Tearing down Docker Compose stack"
    $COMPOSE down -v || true
    rm -rf "$WORKDIR"
    exit "$status"
}
trap cleanup EXIT

echo "==> Extracting locally built package: $OTLP_PACKAGE_PATH"
mkdir -p "$WORKDIR/package"
tar -xzf "$OTLP_PACKAGE_PATH" -C "$WORKDIR/package"
export OTLP_PACKAGE_DIR="$WORKDIR/package/splunk-connect-for-otlp"
mkdir -p "$OTLP_PACKAGE_DIR/local"
cp splunk-inputs-local.conf "$OTLP_PACKAGE_DIR/local/inputs.conf"
# The TA reads HEC tokens at startup, so the token used to send data must be
# configured before Splunk starts.
cat >> "$OTLP_PACKAGE_DIR/local/inputs.conf" <<EOF

[http]
disabled = 0

[http://modinput-smoke]
token = $SMOKE_TOKEN
index = main
indexes = main
disabled = 0
EOF

if [ "${TEST_HEC_PAGINATION:-0}" = 1 ]; then
    echo "==> Creating HEC tokens before the TA starts"
    go run . seed "$OTLP_PACKAGE_DIR/local/inputs.conf"
fi

echo "==> Starting Docker Compose stack with locally built package"
$COMPOSE up -d

echo "==> Waiting for the OTLP HTTP port to accept connections"
timeout=240
elapsed=0
while ! curl -sk --max-time 2 -o /dev/null "https://localhost:${HTTP_PORT}/"; do
    if [ "$elapsed" -ge "$timeout" ]; then
        echo "Timeout: OTLP HTTP port ${HTTP_PORT} was not reachable within ${timeout}s"
        echo "The modular input calls back into Splunk's own management API"
        echo "at https://127.0.0.1:8089 on startup (see internal/auth/auth.go)."
        echo "If that call fails TLS verification against Splunk's own"
        echo "self-signed certificate, the input exits before ever listening."
        exit 1
    fi
    sleep 3
    elapsed=$((elapsed + 3))
done

echo "==> Extracting CA certificate from the splunk container"
$COMPOSE cp splunk:/certs/ca.crt "$CA_CRT"

assert_tls_ok() {
    host="$1"
    if curl -sS --max-time 10 --cacert "$CA_CRT" -o /dev/null "https://${host}:${HTTP_PORT}/v1/logs"; then
        echo "OK: TLS verification succeeded connecting to https://${host}:${HTTP_PORT}"
    else
        echo "FAIL: TLS verification failed connecting to https://${host}:${HTTP_PORT}"
        return 1
    fi
}

echo "==> Checking TLS verification via hostname (control case)"
assert_tls_ok localhost

echo "==> Checking TLS verification via IP literal"
if ! assert_tls_ok 127.0.0.1; then
    echo "The server certificate must carry an IP SAN so that a client"
    echo "dialing it by IP address succeeds, the same way a client dialing"
    echo "it by hostname does."
    exit 1
fi

echo "==> All TLS checks passed"

if [ "${TEST_HEC_PAGINATION:-0}" = 1 ]; then
    echo "==> Checking OTLP authentication with HEC tokens across multiple pages"
    go run . check "$CA_CRT"
fi

echo "==> Sending telemetry through the receiver"
now_ns="$(date +%s)000000000"
send() {
    curl -sS --fail --max-time 10 --cacert "$CA_CRT" -X POST \
        -H "Authorization: Splunk ${SMOKE_TOKEN}" \
        -H "Content-Type: application/json" \
        -d "$2" "https://localhost:${HTTP_PORT}/v1/$1" > /dev/null
}
resource() {
    printf '{"attributes":[{"key":"com.splunk.source","value":{"stringValue":"otlp-smoke-%s"}}]}' "$1"
}
send logs '{"resourceLogs":[{"resource":'"$(resource logs)"',"scopeLogs":[{"logRecords":[{"timeUnixNano":"'"$now_ns"'","body":{"stringValue":"modinput_smoke_log"}}]}]}]}'
send metrics '{"resourceMetrics":[{"resource":'"$(resource metrics)"',"scopeMetrics":[{"metrics":[{"name":"modinput_smoke_metric","gauge":{"dataPoints":[{"asInt":"1","timeUnixNano":"'"$now_ns"'"}]}}]}]}]}'
send traces '{"resourceSpans":[{"resource":'"$(resource traces)"',"scopeSpans":[{"spans":[{"traceId":"5b8efff798038103d269b633813fc60c","spanId":"eee19b7ec3c1b174","name":"modinput_smoke_span","kind":1,"startTimeUnixNano":"'"$now_ns"'","endTimeUnixNano":"'"$now_ns"'"}]}]}]}'

echo "==> Checking the events were indexed by Splunk"
for signal in logs metrics traces; do
    elapsed=0
    printf 'Waiting for %s to be searchable: ' "$signal"
    while true; do
        count="$($COMPOSE exec -T splunk sh -c "curl -ksS --max-time 30 -u \"admin:\$SPLUNK_PASSWORD\" https://localhost:8089/services/search/jobs/export --data-urlencode 'search=search index=main source=\"otlp-smoke-${signal}\" | stats count' -d earliest_time=-30m -d output_mode=csv" 2>/dev/null | tail -n 1 | tr -d '"\r' || true)"
        case "$count" in
            ''|*[!0-9]*) ;;
            *) if [ "$count" -gt 0 ]; then echo "ok"; break; fi ;;
        esac
        if [ "$elapsed" -ge 120 ]; then
            echo ""
            echo "Timeout: ${signal} sent through the OTLP receiver were not indexed within 120s"
            exit 1
        fi
        sleep 5
        elapsed=$((elapsed + 5))
        printf '.'
    done
done

echo "==> All telemetry was indexed"
